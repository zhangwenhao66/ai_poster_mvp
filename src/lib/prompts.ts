export function buildInitialPrompt(input: {
  posterCopy: string;
  smartStyle: boolean;
  hasTemplate: boolean;
}): string {
  const poster = input.posterCopy.trim();
  const lines: string[] = [];
  lines.push("你是餐饮门店海报设计助手。请输出一张可用于打印或线上传播的商业海报。");
  lines.push("要求：信息层级清晰、文字可读（避免过细字体）、配色有食欲感但不俗气；主从分明的前提下画面要「有料」，避免廉价空洞。");
  lines.push("");
  lines.push(
    "【成片水准｜电视广告 / 影视级主视觉】整单应对标品牌 TVC 落版、流媒体贴片或影院预告片单帧的品质：设计感强、高级、第一眼视觉冲击力大，整体和谐统一。严禁过于简单、元素稀少、整版发「素」、像空白 PPT 或手机备忘录截图式的偷懒稿；须在专业广告尺度上主动构建丰富层次——主视觉区、主副标题块、卖点/价格带、装饰图形、色块分割、微纹理、光斑或景深层次等可多线并存，仍须繁而不乱、有呼吸、有记忆点。",
  );
  lines.push(
    "【信息密度与微观可读细节｜禁止「大而空」】画面必须在多个尺度上都有「可看内容」：远看有主焦点与强对比，近看前景/中景/背景均应有可辨细节——例如食材表面的油膜高光与酱汁微粒、器皿釉面的细微反射与划痕、纸张或衬底的纤维/颗粒/压纹、渐变里的色相过渡与噪点层次、装饰线框的粗细变化与断点设计等。严禁整版只剩几块平涂色带加一行字；严禁大面积无纹理、无纵深、无光影变化的死色块凑数。信息要多、层次要细，但仍须主次分明，避免碎成补丁。",
  );
  lines.push(
    "【字体与字形｜禁止默认黑体敷衍】严禁通篇只用单一、无性格的默认黑体/常规黑体/系统标题体压满画面。标题与核心文案须达到「广告美术字 / 杂志封面字 / 路牌招贴字」级别的艺术感：笔画可有设计性变化（粗细对比、断笔、连笔、几何切割、弧化字腔、微倾斜动势等），整体字形气质必须与品类与画面风格强绑定——高端正餐偏典雅衬线或克制宋变体；新中式可榜书、行楷笔意或招牌手写；轻食咖啡可现代几何无衬线或日系精炼黑体；烘焙甜品可柔和圆体或插画风混排。可做字重对比、字距节奏、叠印/镂空/细描边/局部烫色等，但须印刷级清晰、边缘干净。中英混排须同一套视觉语言。禁止字糊、禁止办公软件感默认标题、禁止廉价描边发光字。",
  );
  lines.push(
    "【再强调｜字形即设计】把「字」当作主设计元素之一来刻画：主标题占画面显著面积时，字形本身要有雕塑感与留白节奏，而不是单纯放大系统字体；副文案可用对比强烈的第二种字系形成层级，但仍须高级、统一、有手工或精排质感。",
  );
  lines.push(
    "【用户素材的影视级优化（保真前提下）】在下一节「商品/门店必须与成稿一致」的前提下，允许对用户上传照片做专业级提质：重塑光影与体积感、统一色彩分级与氛围、提升细节与锐度、去杂光脏点与轻微畸变校正；可为整体构图与冲击力做适度透视、裁切与「更上镜」的取景/机位感微调。以上优化须服务于整张贴片级和谐与高级感，不得借机把商品或门店换成另一种物体。",
  );
  lines.push("");
  lines.push(
    "【最高优先级｜用户素材里的商品/门店必须与成稿一致】用户上传的实拍素材用于展示真实在售菜品、饮品、包装、门店外观、招牌或灯箱等。成稿中出现的每一道主菜品、每一款饮品、包装形态、门面与招牌主体，必须与对应素材图指向同一对象、保留可辨认的同一性：禁止换成另一道菜、另一款饮品、另一家店面或「看起来差不多」的替代品；禁止用通用示意食物、随机饮品杯、虚构门面或库存风商品图替代用户实拍。",
  );
  lines.push(
    "若使用模板：模板参考图提供版式结构、配色气质、装饰语言，以及**字体样式与画面细节层次的视觉范本**（须尽量对齐，见下方「风格参考图对齐」）；但不得用模板里示意性的菜品/饮品/门面图示去覆盖、替换或「重画成另一款」用户后续素材中的真实商品外观。主视觉中的食物与饮品须明显来源于用户素材的再现，而不是模板上另一盘菜的画风。",
  );
  lines.push(
    "禁止重绘成另一种商品、改变盛装容器与品牌标识、改变菜品装盘结构、把门头/招牌改成另一家店。素材偏糊时：宁可保留可辨认轮廓与关键特征，也不要编造与用户图不符的细节。装饰性插画、剪影、小图标仅可作点缀，不得取代用户实拍商品成为画面主商品。",
  );
  lines.push("");
  if (input.hasTemplate) {
    lines.push(
      "用户提供了模板参考图（通常排在参考图的第一张）：请尽量吸收模板的版式气质、配色与装饰元素，但必须融合后续用户素材图的主体信息，不要只做简单拼贴。",
    );
    lines.push(
      "【风格参考图对齐｜字体与细节向模板看齐】第一张模板参考图在标题/副标题的字形气质、字重与层级、字距与行距节奏、角标丝带分割线、几何装饰、微纹理与光感层次、色块形状与透明度关系等方面通常已是成熟设计。成稿在**版式与视觉语言**上须与该参考图**高度同系**：字体样式应明显继承参考图中的字形设计方向（笔画粗细对比、衬线/无衬线/手写榜书等类别、装饰性笔画处理），不要随意换成与参考图气质冲突的另一套字体或「默认黑体重新排版」；装饰元素、线框语言、点缀图形的风格与密度也应尽量与参考图保持一致或在其基础上微调，而不是推倒重来成另一种画风。用户提供的真实文案替换模板假字时，仍须套用与参考图一致或极接近的**字体样式与层级关系**；画面信息密度与精致度不得低于参考图所体现的设计水准。",
    );
    lines.push(
      "注意：上一致性指**风格、字体与装饰细节**；盘中/杯中的具体商品外观仍须严格来自用户后续实拍素材，不可用模板里的示意菜品替代——风格跟模板走，商品跟用户图走。",
    );
    lines.push(
      "模板参考图左上角通常带有「稿定设计」字样与「YOUR LOGO」占位，属于模板素材自带的无关元素。成稿中必须去掉画面左上角的「稿定设计」「YOUR LOGO」及同类占位文字与假 Logo，不要出现在最终海报上；最终画面只应包含下方用户提供的真实文案与合理排版装饰。",
    );
  } else if (input.smartStyle) {
    lines.push(
      "【智能风格｜无版式参考图】用户未选模板，仅以你收到的用户素材图为视觉锚点。请先「读图」：判断品类与场景气质（如热食/饮品/烘焙/店面门头/特写菜品等）、环境光与主色倾向，再据此确定整套海报的色相、对比度与材质感；背景与装饰色应从照片中取色或做和谐衍生，禁止与素材气质冲突的随机滤镜风。主视觉放大与风格化不得把实拍商品画成另一种商品。",
    );
    lines.push(
      "版式要「满而不乱」：在把下方用户文案完整、清晰排进画面的前提下，主动构建专业海报层次——建议包含明确主视觉区（放大最有食欲或最有识别度的一张/一角）、主标题块、1～2 条辅助卖点或副标题条带；可用半透明色块、轻几何分割、细线框、小角标/丝带形标签、极低对比的纸张或噪点纹理托底，让信息有落点、画面有呼吸。避免大片空白却又不加设计结构的偷懒版式。",
    );
    lines.push(
      "可适当增加与气质相符的点缀图形（如食材剪影、蒸汽/水珠、麦穗、叶片、简约图标等），须扁平或微拟物、面积小、不抢主体；可加一条与主色协调的细装饰线或重复纹样条，增强「成套设计」感。禁止堆砌廉价贴纸风或与内容无关的随机插画。",
    );
    lines.push(
      "字体与层级：主文案最大最醒目，次要信息缩小并降低饱和度；须遵守上文「禁止默认黑体敷衍」的字体气质要求。若需英文点缀，须与中文风格统一。整体观感应接近线下门店可用的印刷级单页海报：远看有焦点，近看有细节，绝不是「把字直接叠在原图上」的粗糙合成。",
    );
  }
  lines.push("海报需要呈现的核心文案/要素如下（请合理排版，不要遗漏关键信息）：");
  lines.push(poster);
  lines.push(
    "如有多张参考图：请综合理解每张图的信息层级，突出主招牌/主菜品；避免画面拥挤。除非用户明确要求，否则不要自行添加虚构价格、电话、地址。",
  );
  lines.push(
    input.hasTemplate
      ? "最终观感：画面丰富、冲击力强，整体达到影视/TVC 级水准；**字体、装饰层次与细节精致度应与第一张模板参考图尽量同系**，像同一套模板系下的新稿；同时商品/门店仍须来自用户实拍，不被模板示意图替换。"
      : "最终观感：画面丰富、冲击力强、字体与图形有专业广告设计感，整体达到影视/TVC 级水准；同时用户应能明确感到「海报上卖的还是我们拍的那几样东西、还是这家店」，而不是被换成别的商品或别的店。",
  );
  return lines.join("\n");
}

/** 单张菜品图：盘中同一道菜；允许影视级光影色彩与细节提质；背景与画面须丰富、TVC 美食广告级。 */
export function buildDishPhotoPrompt(): string {
  const lines: string[] = [];
  lines.push(
    "你是顶级美食静物摄影师与后期总监。用户上传的是一道菜的「随手拍」参考图，可能存在对焦不实、手抖、弱光噪点、强压缩或分辨率偏低等问题。",
  );
  lines.push("");
  lines.push(
    "【成片水准｜电视广告 / 流媒体美食贴片级】单帧也要达到品牌美食 TVC、高端外卖平台头图或影院食品广告静帧的水准：整体高级、有设计感、视觉冲击力大、和谐耐看。严禁「只有一盘菜 + 大面积死空白或纯色底」的单调画面；须在专业美食广告尺度上丰富画面——多层景深、台面与背景材质层次、柔和光斑、轻薄蒸汽或水珠、餐具与道具的次要层次、受控的装饰元素等可多线铺陈，仍须主从分明、不抢盘中主体。",
  );
  lines.push(
    "【微观与介质细节｜禁止空洞】食物与环境须布满可信的微观信息：肉纹/蔬菜纤维/面包气孔/酱汁挂边与油星、盘面水痕与高光、桌面的木纹石纹颗粒、背景虚化里的光斑形状与层次、餐具金属的菲涅尔高光等；禁止涂抹成塑料块、禁止无纹理平涂。画面信息密度要高，但主体仍是那道菜。",
  );
  lines.push(
    "【最高优先级｜食物必须与参考图是「同一盘东西」】盘中呈现的食物（含同盘内的主料、配菜、酱汁形态、堆叠层次、刀口与焦痕位置、葱花/蒜末等可见点缀的相对位置）必须与参考图在内容与识别上保持一致：仍是同一道菜，而不是换了一盘或「升级成另一道菜」。禁止把菜品变成另一种食材、另一道菜或另一个物体；禁止增减食材、改刀重组摆盘、改变食物轮廓与酱料形状的语义。",
  );
  lines.push(
    "【盘中食物｜同一道菜前提下的影视级优化】在上一节保真前提下，允许对用户实拍做专业级提质：重塑落在食物上的光影、高光油润与体积感，做与整帧画面统一的色彩分级与白平衡，增强纹理、清晰度与降噪；允许为食欲与构图张力做轻微的透视或「更上镜」的机位感微调，但不得改变菜肴是谁、长什么样。参考图看不清的部位：宁可略柔也不要编造与原图矛盾的新细节。禁止把煎痕/肉纹等关键特征磨没或替换成另一块肉/另一棵菜的画法。",
  );
  lines.push("");
  lines.push(
    "【允许大改动的范围｜背景、台面与盘外搭配】完整替换原图的桌面、桌布、餐厅环境、墙面、杂乱反光、塑料垫、打包盒边缘等；重新设计台面/托盘/石板/木纹/大理石等承载面（须与菜品气质匹配且视觉信息丰富）。盘外搭配道具（旁侧杯碟、公筷架、装饰垫纸、与主盘分离的点缀物等）允许更换或精心布置，服务于 TVC 级氛围。若原图有手指、筷子夹食、手入镜，可去掉手部，只保留盘中成品。水印、二维码、价签、杂乱文字一律去除，不要虚构店铺信息。",
  );
  lines.push("");
  lines.push(
    "【若有画面内文字】须具备广告美术字或精排杂志字级艺术感（笔形有设计、与场景气质绑定），禁止默认系统黑体/常规黑体大字压图；若无文字需求则不要硬加。",
  );
  lines.push("");
  lines.push(
    "【输出标准】食物区域须达到商业美食广告可读清晰度：主体边缘利落、主要纹理可辨，禁止厚涂抹、油画感或塑料磨皮。背景与承载面可有明显虚化与层次，整体通透、有电影感。",
  );
  lines.push("");
  lines.push(
    "【禁止偷懒】禁止只磨皮提亮而几乎不换场景；禁止输出与原图几乎无差别；若原图偏糊，禁止成片仍整体发虚。最终应让用户感到：光影、色彩、场景层次与冲击达到贴片级广告，但盘里仍是同一道菜。",
  );
  return lines.join("\n");
}

export function buildModifyPrompt(
  editInstruction: string,
  context: "poster" | "dish" = "poster",
): string {
  const t = editInstruction.trim();
  const head =
    context === "dish"
      ? "盘中须仍是同一道菜（禁止换成别的东西）；允许在保真前提下继续强化影视级光影、色彩分级、微观细节与背景层次，使画面更饱满、更贴片级高级。可按用户意见调整背景丰富度、台面、道具与氛围；禁止重绘成另一道菜。若有字，须保持美术字级艺术感，禁止默认黑体。"
      : "在尽量保持当前海报整体构图与文案商业信息不变的前提下，按用户修改意见编辑。商品/门店须保持同一识别度，禁止换成另一种物品或另一家店。若画面明显承袭某套模板化版式与装饰，修改时应**延续当前稿中的字体气质、线框与点缀图形语言**，不要随意改成另一套风格或退回默认黑体。须保持或强化：画面信息密度、微观细节与 TVC 级冲击力。可继续优化用户素材的光影、色彩与细节以统一全片高级感。";
  return [head, "修改应尽量局部化：只调整需要调整的区域，其它区域尽量少改动。", "修改意见如下：", t].join("\n");
}
