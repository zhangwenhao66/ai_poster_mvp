export function buildInitialPrompt(input: {
  posterCopy: string;
  smartStyle: boolean;
  hasTemplate: boolean;
}): string {
  const poster = input.posterCopy.trim();
  const lines: string[] = [];
  lines.push("你是餐饮门店海报设计助手。请输出一张可用于打印或线上传播的商业海报。");
  lines.push("要求：信息层级清晰、文字可读（避免过细字体）、配色有食欲感但不俗气、留白克制。");
  lines.push("");
  lines.push(
    "【最高优先级｜用户素材里的商品/门店必须与成稿一致】用户上传的实拍素材用于展示真实在售菜品、饮品、包装、门店外观、招牌或灯箱等。成稿中出现的每一道主菜品、每一款饮品、包装形态、门面与招牌主体，必须与对应素材图指向同一对象、保留可辨认的同一性：禁止换成另一道菜、另一款饮品、另一家店面或「看起来差不多」的替代品；禁止用通用示意食物、随机饮品杯、虚构门面或库存风商品图替代用户实拍。",
  );
  lines.push(
    "若使用模板：模板参考图仅提供版式结构、配色气质与装饰语言；不得用模板里示意性的菜品/饮品/门面图示去覆盖、替换或「重画成另一款」用户后续素材中的真实商品外观。主视觉中的食物与饮品须明显来源于用户素材的再现，而不是模板上另一盘菜的画风。",
  );
  lines.push(
    "允许对素材主体做：为版式融合所需的裁切、轻微透视与明暗调整、与整体海报协调的清晰化/去噪/对比度优化。禁止重绘成另一种商品、改变盛装容器与品牌标识、改变菜品装盘结构、把门头/招牌改成另一家店。素材偏糊时：宁可保留可辨认轮廓与关键特征，也不要编造与用户图不符的细节。装饰性插画、剪影、小图标仅可作点缀，不得取代用户实拍商品成为画面主商品。",
  );
  lines.push("");
  if (input.hasTemplate) {
    lines.push(
      "用户提供了模板参考图（通常排在参考图的第一张）：请尽量吸收模板的版式气质、配色与装饰元素，但必须融合后续用户素材图的主体信息，不要只做简单拼贴。",
    );
    lines.push(
      "模板参考图左上角通常带有「稿定设计」字样与「YOUR LOGO」占位，属于模板素材自带的无关元素。成稿中必须去掉画面左上角的「稿定设计」「YOUR LOGO」及同类占位文字与假 Logo，不要出现在最终海报上；最终画面只应包含下方用户提供的真实文案与合理排版装饰。",
    );
  } else if (input.smartStyle) {
    lines.push(
      "【智能风格｜无版式参考图】用户未选模板，仅以你收到的用户素材图为视觉锚点。请先「读图」：判断品类与场景气质（如热食/饮品/烘焙/店面门头/特写菜品等）、环境光与主色倾向，再据此确定整套海报的色相、对比度与材质感；背景与装饰色应从照片中取色或做和谐衍生，禁止与素材气质冲突的随机滤镜风。主视觉放大与风格化不得把实拍商品画成另一种商品。",
    );
    lines.push(
      "版式要「满而不乱」：在把下方用户文案完整、清晰排进画面的前提下，主动构建专业海报层次——建议包含明确主视觉区（放大最有食欲或最有识别度的一张/一角）、主标题块、1～2 条辅助卖点或副标题条带；可用半透明色块、轻几何分割、细线框、小角标/丝带形标签、极低对比的纸张或噪点纹理托底，让信息有落点、画面有呼吸。避免大片空白却又不加设计结构的偷懒版式。",
    );
    lines.push(
      "可适当增加与气质相符的点缀图形（如食材剪影、蒸汽/水珠、麦穗、叶片、简约图标等），须扁平或微拟物、面积小、不抢主体；可加一条与主色协调的细装饰线或重复纹样条，增强「成套设计」感。禁止堆砌廉价贴纸风或与内容无关的随机插画。",
    );
    lines.push(
      "字体与层级：主文案最大最醒目，次要信息缩小并降低饱和度；保证笔画清晰、边缘干净。若需英文点缀，须与中文风格统一。整体观感应接近线下门店可用的印刷级单页海报：远看有焦点，近看有细节，绝不是「把字直接叠在原图上」的粗糙合成。",
    );
  }
  lines.push("海报需要呈现的核心文案/要素如下（请合理排版，不要遗漏关键信息）：");
  lines.push(poster);
  lines.push(
    "如有多张参考图：请综合理解每张图的信息层级，突出主招牌/主菜品；避免画面拥挤。除非用户明确要求，否则不要自行添加虚构价格、电话、地址。",
  );
  lines.push(
    "最终观感：设计可以更专业、更吸睛，但用户应能明确感到「海报上卖的还是我们拍的那几样东西、还是这家店」，而不是被换成别的商品或别的店。",
  );
  return lines.join("\n");
}

/** 单张菜品图：盘中食物与原图同物同貌（仅高清化），背景/台面/盘外搭配可重塑。 */
export function buildDishPhotoPrompt(): string {
  const lines: string[] = [];
  lines.push(
    "你是顶级美食静物摄影师与后期总监。用户上传的是一道菜的「随手拍」参考图，可能存在对焦不实、手抖、弱光噪点、强压缩或分辨率偏低等问题。",
  );
  lines.push("");
  lines.push(
    "【最高优先级｜食物必须与参考图是「同一盘东西」】盘中呈现的食物（含同盘内的主料、配菜、酱汁形态、堆叠层次、刀口与焦痕位置、葱花/蒜末等可见点缀的相对位置）必须与参考图在内容与细节上保持一致：看起来像同一张照片被「拍清楚了」，而不是换了一盘菜或「升级成另一道菜」。禁止把菜品变成另一种食材、另一道菜或另一个物体；禁止增减食材、改刀重组摆盘、改变食物轮廓与纹理走向。",
  );
  lines.push(
    "【仅允许对食物做的处理＝高清化与真实还原】对盘中食物只允许：去糊、锐化、降噪、微对比与真实质感还原，使边缘与纹理在视觉上更清晰；禁止为了「更好看」而重绘、液化变形、替换纹理、或凭想象「补全」成与参考图不一致的细节。参考图看不清的地方：宁可保持模糊边界也不要编造新细节。禁止对食物做会改变其外观语义的美颜、换色、换质感（例如把煎痕磨没、把肉片改成另一块肉的外观）。",
  );
  lines.push("");
  lines.push(
    "【允许大改动的范围｜背景、台面与盘外搭配】完整替换原图的桌面、桌布、餐厅环境、墙面、杂乱反光、塑料垫、打包盒边缘等；重新设计台面/托盘/石板/木纹/大理石等承载面（须与菜品气质匹配）。盘外、画面中的搭配道具（如旁侧杯碟、公筷架、装饰垫纸、与主盘分离的点缀物）允许更换或重新布置，使画面更干净高级。若原图有手指、筷子夹食、手入镜，可去掉手部，只保留盘中成品。水印、二维码、价签、杂乱文字一律去除，不要虚构店铺信息。",
  );
  lines.push("");
  lines.push(
    "【超清输出标准】成片在食物区域应达到商业静物摄影可读清晰度：主体边缘相对利落、主要纹理可辨，禁止食物区域发糊、厚涂抹、油画感或塑料磨皮感。整体观感干净通透；背景与承载面可明显虚化以突出主体。",
  );
  lines.push("");
  lines.push("【光影】重新设计布光（不必沿用原图现场光），例如侧向/侧顶主光、柔化补光、轻薄轮廓光，让食物从背景中分离出来；但落在食物上的明暗关系不得改变食物的形状识别与细节位置含义。");
  lines.push("");
  lines.push(
    "【色彩】可对背景、台面、环境做完整色彩分级与氛围提升。对盘中食物：仅做与「还原真实」一致的白平衡与曝光校正，以及为印刷/屏幕可读所需的轻微对比；禁止对食物做会改变其颜色的「风味调色」（如把肉色变深红、把蔬菜改成更翠的另一种绿），以免看起来像换了食材。",
  );
  lines.push("");
  lines.push(
    "【禁止偷懒】禁止只磨皮提亮而保留杂乱背景；禁止输出与原图几乎无差别；若原图偏糊，禁止食物区域仍然整体发虚。最终画面应让用户明确感到：环境、台面与光感升级到商业级，但盘里的东西仍是同一盘、细节未被改写。",
  );
  return lines.join("\n");
}

export function buildModifyPrompt(
  editInstruction: string,
  context: "poster" | "dish" = "poster",
): string {
  const t = editInstruction.trim();
  const head =
    context === "dish"
      ? "盘中食物必须与当前参考图保持同一道菜、同一摆盘与同一细节（仅允许更清晰的去糊/锐化/降噪，禁止改食材、改形状、改细节或把菜变成别的东西）。可按用户意见调整背景、台面、盘外搭配道具与整体光影氛围；若用户要求更清晰，只强化真实清晰度，禁止重绘食物外观。"
      : "在尽量保持当前海报整体构图与文案商业信息不变的前提下，按用户修改意见编辑。画面中来自用户素材的商品、饮品、门面与招牌须保持同一识别度，禁止在修改中换成另一种物品或另一家店；仅允许版式、装饰、色调、清晰度等调整。";
  return [head, "修改应尽量局部化：只调整需要调整的区域，其它区域尽量少改动。", "修改意见如下：", t].join("\n");
}
