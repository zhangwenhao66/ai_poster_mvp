export function buildInitialPrompt(input: {
  posterCopy: string;
  smartStyle: boolean;
  hasTemplate: boolean;
}): string {
  const poster = input.posterCopy.trim();
  const lines: string[] = [];
  lines.push("你是餐饮门店海报设计助手。请输出一张可用于打印或线上传播的商业海报。");
  lines.push("要求：信息层级清晰、文字可读（避免过细字体）、配色有食欲感但不俗气、留白克制。");
  if (input.hasTemplate) {
    lines.push(
      "用户提供了模板参考图（通常排在参考图的第一张）：请尽量吸收模板的版式气质、配色与装饰元素，但必须融合后续用户素材图的主体信息，不要只做简单拼贴。",
    );
    lines.push(
      "模板参考图左上角通常带有「稿定设计」字样与「YOUR LOGO」占位，属于模板素材自带的无关元素。成稿中必须去掉画面左上角的「稿定设计」「YOUR LOGO」及同类占位文字与假 Logo，不要出现在最终海报上；最终画面只应包含下方用户提供的真实文案与合理排版装饰。",
    );
  } else if (input.smartStyle) {
    lines.push(
      "【智能风格｜无版式参考图】用户未选模板，仅以你收到的用户素材图为视觉锚点。请先「读图」：判断品类与场景气质（如热食/饮品/烘焙/店面门头/特写菜品等）、环境光与主色倾向，再据此确定整套海报的色相、对比度与材质感；背景与装饰色应从照片中取色或做和谐衍生，禁止与素材气质冲突的随机滤镜风。",
    );
    lines.push(
      "版式要「满而不乱」：在把下方用户文案完整、清晰排进画面的前提下，主动构建专业海报层次——建议包含明确主视觉区（放大最有食欲或最有识别度的一张/一角）、主标题块、1～2 条辅助卖点或副标题条带；可用半透明色块、轻几何分割、细线框、小角标/丝带形标签、极低对比的纸张或噪点纹理托底，让信息有落点、画面有呼吸。避免大片空白却又不加设计结构的偷懒版式。",
    );
    lines.push(
      "可适当增加与气质相符的点缀图形（如食材剪影、蒸汽/水珠、麦穗、叶片、简约图标等），须扁平或微拟物、面积小、不抢主体；可加一条与主色协调的细装饰线或重复纹样条，增强「成套设计」感。禁止堆砌廉价贴纸风或与内容无关的随机插画。",
    );
    lines.push(
      "字体与层级：主文案最大最醒目，次要信息缩小并降低饱和度；保证笔画清晰、边缘干净。若需英文点缀，须与中文风格统一。整体观感应接近线下门店可用的印刷级单页海报：远看有焦点，近看有细节，绝不是「把字直接叠在原图上」的粗糙合成。",
    );
  }
  lines.push("海报需要呈现的核心文案/要素如下（请合理排版，不要遗漏关键信息）：");
  lines.push(poster);
  lines.push(
    "如有多张参考图：请综合理解每张图的信息层级，突出主招牌/主菜品；避免画面拥挤。除非用户明确要求，否则不要自行添加虚构价格、电话、地址。",
  );
  return lines.join("\n");
}

/** 单张菜品图：保留食物本体与摆盘，环境与光影可大幅重塑，追求惊艳的菜单头图效果。 */
export function buildDishPhotoPrompt(): string {
  const lines: string[] = [];
  lines.push(
    "你是顶级美食静物摄影师与后期总监。用户上传的是一道菜的「随手拍」参考图，可能存在对焦不实、手抖、弱光噪点、强压缩或分辨率偏低等问题。你的目标不是「轻微修图」，而是输出一张看起来像在专业摄影棚里、用高端机身与中长焦微距镜头、三脚架稳定拍摄的单帧成片——第一眼就要比原图明显更惊艳、更贵、更有食欲，适合直接做线上菜单头图、外卖主图与商业宣传图。",
  );
  lines.push("");
  lines.push(
    "【超清与细节重建｜输入再糊也要输出顶级清晰度】即使用户图整体模糊、发虚、马赛克感或细节丢失，你仍要在不篡改菜品身份的前提下，把「这道菜应有的清晰样子」补全：",
  );
  lines.push(
    "- 解析度与锐利度：成片必须达到商业静物摄影的清晰标准——主体边缘利落、食材纹理可辨（如肉纹、蔬菜纤维、面包气孔、煎烤焦边、酱汁层次），禁止输出发糊、涂抹、油画感或过度磨皮成塑料的食物表面。",
  );
  lines.push(
    "- 细节推断：在参考图看不清的区域，按该菜品的常理与同类食物的典型结构，合理推断并补全细节（例如酱汁边缘、配料颗粒、脆皮与柔润肉质的分界），但必须与参考图能辨认的信息一致，禁止凭空多加一种食材或把菜改成另一道菜。",
  );
  lines.push(
    "- 整体观感：最终画面应像影棚里用柔光箱 + 反光板 + 可控景深拍出的高清成片，而不是「手机随手拍 + 滤镜」。全屏观感干净、通透、无脏噪点堆积（可适当降噪但保留真实质感）。",
  );
  lines.push("");
  lines.push(
    "【必须锁定｜只允许动环境，不动菜】菜品本身必须与参考图一致：食材种类、分量感、摆盘结构、刀工层次、酱汁与配料位置、盛放器皿的大致器型与颜色倾向须保持一致；禁止换成另一道菜、禁止重组摆盘。允许对食物表面做「摄影级」强化：更清晰的高光与油润感、更分明的纹理，但不要改变食物是什么。若原图有手指、筷子夹着食物、手入镜等，可去掉手部，只保留盘中成品。水印、二维码、价签、杂乱文字一律去除，不要虚构店铺信息。",
  );
  lines.push("");
  lines.push(
    "【必须大胆重做｜背景与承载面】原图的桌面、桌布、餐厅环境、墙面、反光、塑料垫、打包盒边缘等——一律视为可丢弃信息。请完整替换为一套新的、干净且更高级的场景，而不是在原背景上「抹一抹」。台面/托盘/石板/木纹/大理石/深色岩板/哑光陶瓷等任选其一或组合，须与菜品气质匹配（中餐可偏暖木与深色石板；日料可极简浅灰与留白；烧烤/炸物可略偏深色衬底突出油亮；甜品可明亮高调或柔粉渐变）。背景要有层次：可含柔和渐变、虚化的厨房光斑、极淡的景深光斑，但禁止杂乱杂物。",
  );
  lines.push("");
  lines.push("【光影必须重塑】禁止沿用原图的平淡顶光或杂乱现场光。请重新设计布光方案，例如：");
  lines.push(
    "- 主光：约 45° 侧向或侧顶，塑造体积与层次；",
  );
  lines.push("- 补光：柔化阴影，保留食材细节不死黑；");
  lines.push("- 轮廓/逆光：薄逆光或边缘高光，让食物从背景里「抠」出来，油边与汤汁高光要漂亮；");
  lines.push("- 整体对比：比原图更有戏剧性但仍商业可卖，避免脏灰与死黑一团。");
  lines.push("");
  lines.push(
    "【色彩与氛围要更丰富】做完整的色彩分级：主色与辅助色呼应（食材暖则背景可冷一点做对比，或同色系做高级调和）。提升饱和度与新鲜度到「屏幕上看就想点」的程度，但避免荧光、假艳、廉价滤镜感。可适当增强酱汁红亮、蔬菜翠绿、肉类多汁感，让画面更「润」。",
  );
  lines.push("");
  lines.push(
    "【质感与景深】食物主体锐利；背景与远处台面明显虚化（大光圈静物感）。可在合理范围内增加极轻的蒸汽、细密水珠、油光高光点，但必须自然、不糊成一片。",
  );
  lines.push("");
  lines.push(
    "【禁止偷懒】禁止只磨皮、只提亮、只轻微调色而保留原杂乱背景；禁止输出与原图几乎无差别的结果；若原图偏糊，禁止输出仍然整体发虚的「假高清」。最终画面必须让用户感到：环境、光、色、清晰度整体都升级到商业宣传级别，但菜还是那道菜。",
  );
  return lines.join("\n");
}

export function buildModifyPrompt(
  editInstruction: string,
  context: "poster" | "dish" = "poster",
): string {
  const t = editInstruction.trim();
  const head =
    context === "dish"
      ? "在保持菜品本体造型与识别度不变的前提下，按用户意见继续优化图像；可大胆调整背景、台面、整体光影与色彩氛围；若用户提出更清晰、更锐利、更棚拍感等需求，在合理范围内强化细节与清晰度，避免把食物磨成塑料感。"
      : "在尽量保持当前海报整体构图与商业信息不变的前提下，按用户的修改意见进行图像编辑。";
  return [head, "修改应尽量局部化：只调整需要调整的区域，其它区域尽量少改动。", "修改意见如下：", t].join("\n");
}
